// Crie um vetor com nome de seus familiares.
// com seis nomes.

// use todos os comandos vistos em vetores após criar a lista.

const familiares = ["Carvalho", "Coroa", "Veinho", "Colombia", "Buiu", "China"];
console.log("Lista de familiares:", familiares);

// Adicione mais um nome a lista.
familiares.push("Luiza");
console.log("n\Lista após adicionar um nome:", familiares);

// Remova apenas o primeiro elemento da lista.
familiares.shift();
console.log("n\Lista após remover o primeiro elemento:", familiares);

// Remova apenas o segundo elemento da lista.
familiares.splice(1, 1);
console.log("n\Lista após remover o segundo elemento:", familiares);  

// Remova apenas o último elemento da lista.
familiares.pop();
console.log("n\Lista após remover o último elemento:", familiares);




